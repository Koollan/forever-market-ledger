export type Good = { name: string; cat: GoodCat; tier: number; profs?: string[]; est: true; src: string };

const PROFS: Partial<Record<GoodCat, string[]>> = { Meat: ["Cooking"], Egg: ["Cooking"], Fish: ["Cooking", "Fishing"] };
